let loadedHomeworkSessions = [];

function normalizeHwQuestion(q) {
  if (typeof q === 'string') return { text: q, category: null, assignedTo: '' };
  return { text: q.text || '', category: q.category || null, assignedTo: q.assignedTo || '' };
}

async function loadHomework() {
  const listEl = document.getElementById('homeworkList');
  const { data: sessions, error } = await sb.from('homework_sessions').select('*').order('created_at', { ascending: false });
  if (error) { listEl.innerHTML = `<div class="empty-state">Couldn't load homework.</div>`; return; }
  loadedHomeworkSessions = sessions || [];
  if (!sessions || !sessions.length) {
    listEl.innerHTML = `<div class="empty-state">No homework posted yet.</div>`;
    updateHomeHomeworkCard(null, []);
    return;
  }
  const { data: answers } = await sb.from('homework_answers').select('*').order('created_at', { ascending: true });
  const answersBySession = {};
  (answers || []).forEach(a => {
    (answersBySession[a.session_id] ||= []).push(a);
  });

  updateHomeHomeworkCard(sessions[0], answersBySession[sessions[0].id] || []);

  listEl.innerHTML = sessions.map(s => homeworkCardHtml(s, answersBySession[s.id] || [])).join('');

  listEl.querySelectorAll('.hw-answer-form').forEach(form => {
    form.addEventListener('submit', async (e) => {
      e.preventDefault();
      if (!currentProfile) return;
      const sessionId = form.dataset.session;
      const qIndex = Number(form.dataset.qindex);
      const textarea = form.querySelector('textarea');
      const text = textarea.value.trim();
      if (!text) return;
      const { error } = await sb.from('homework_answers').insert({
        session_id: sessionId, question_index: qIndex,
        author: currentProfile.display_name, author_id: currentProfile.id,
        answer: text
      });
      if (error) { toast('Could not submit answer.', true); return; }
      toast('Answer submitted!');
      loadHomework();
    });
  });

  listEl.querySelectorAll('.hw-assign-input').forEach(input => {
    input.addEventListener('change', async () => {
      const sessionId = input.dataset.session;
      const qIdx = Number(input.dataset.qindex);
      const session = loadedHomeworkSessions.find(s => s.id === sessionId);
      if (!session) return;
      const questions = (Array.isArray(session.questions) ? session.questions : []).map(normalizeHwQuestion);
      questions[qIdx] = { ...questions[qIdx], assignedTo: input.value.trim() };
      const { error } = await sb.from('homework_sessions').update({ questions }).eq('id', sessionId);
      if (error) { toast('Could not save assignment.', true); return; }
      session.questions = questions;
      toast('Assignment saved.');
      loadHomework();
    });
  });
}
function homeworkCardHtml(s, answers) {
  const due = s.due_date ? new Date(s.due_date + 'T00:00:00').toLocaleDateString(undefined, { month: 'short', day: 'numeric' }) : null;
  const questions = Array.isArray(s.questions) ? s.questions : [];

  const assignedIdx = [];
  const unassignedIdx = [];
  questions.forEach((qRaw, idx) => {
    const q = normalizeHwQuestion(qRaw);
    (q.assignedTo ? assignedIdx : unassignedIdx).push(idx);
  });

  function fullQuestionCard(idx) {
    const q = normalizeHwQuestion(questions[idx]);
    const qAnswers = answers.filter(a => a.question_index === idx);
    return `
      <div class="hw-question">
        <div class="hw-question-head">
          <div class="hw-question-text">${idx + 1}. ${escapeHtml(q.text)}</div>
          ${q.category ? `<span class="hw-category">${escapeHtml(q.category)}</span>` : ''}
        </div>
        <label class="hw-assign-row">Assigned to
          <input type="text" class="hw-assign-input" data-session="${s.id}" data-qindex="${idx}" value="${escapeHtml(q.assignedTo)}" placeholder="Name">
        </label>
        <div class="hw-answers">
          ${qAnswers.length ? qAnswers.map(a => `
            <div class="hw-answer">
              <div class="hw-answer-author">${escapeHtml(a.author)}</div>
              ${escapeHtml(a.answer)}
            </div>`).join('') : `<div class="hw-answer" style="opacity:0.6">No answers yet.</div>`}
        </div>
        <form class="hw-answer-form" data-session="${s.id}" data-qindex="${idx}">
          <textarea rows="2" placeholder="Your 3–5 minute synopsis…"></textarea>
          <button class="btn btn-primary btn-sm" type="submit">Post</button>
        </form>
      </div>`;
  }

  function compactRow(idx) {
    const q = normalizeHwQuestion(questions[idx]);
    return `
      <div class="hw-compact-row">
        <div class="hw-compact-text">${idx + 1}. ${escapeHtml(q.text)}</div>
        <input type="text" class="hw-assign-input hw-assign-input-compact" data-session="${s.id}" data-qindex="${idx}" value="" placeholder="Assign to…">
      </div>`;
  }

  // Group the unassigned pool by category for easier browsing.
  const unassignedByCategory = {};
  unassignedIdx.forEach(idx => {
    const cat = normalizeHwQuestion(questions[idx]).category || 'Other';
    (unassignedByCategory[cat] ||= []).push(idx);
  });

  return `
  <div class="hw-card">
    <div class="hw-head">
      <div>
        <div class="hw-title">${escapeHtml(s.title)}</div>
        <div class="hw-due">Posted by ${escapeHtml(s.created_by)}${due ? ' · due ' + due : ''} · ${assignedIdx.length} of ${questions.length} assigned</div>
      </div>
    </div>

    ${assignedIdx.length ? assignedIdx.map(fullQuestionCard).join('') : `<div class="empty-state" style="margin-top:16px;">No one's picked a question yet — assign one from the list below.</div>`}

    ${unassignedIdx.length ? `
      <details class="hw-unassigned">
        <summary>Unassigned questions (${unassignedIdx.length}) — browse &amp; assign</summary>
        <div class="hw-unassigned-body">
          ${Object.entries(unassignedByCategory).map(([cat, idxs]) => `
            <div class="hw-category-group">
              <div class="hw-category-group-title">${escapeHtml(cat)}</div>
              ${idxs.map(compactRow).join('')}
            </div>
          `).join('')}
        </div>
      </details>
    ` : ''}
  </div>`;
}

