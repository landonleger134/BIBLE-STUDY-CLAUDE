function movableFeasts(year) {
  const easter = computeEaster(year);
  return [
    { date: addDays(easter, -46), name: "Ash Wednesday", holyDay: false },
    { date: addDays(easter, -7), name: "Palm Sunday", holyDay: false },
    { date: addDays(easter, -3), name: "Holy Thursday", holyDay: false },
    { date: addDays(easter, -2), name: "Good Friday", holyDay: false },
    { date: easter, name: "Easter Sunday", holyDay: false },
    { date: addDays(easter, 39), name: "Ascension of the Lord", holyDay: true },
    { date: addDays(easter, 49), name: "Pentecost", holyDay: false },
    { date: addDays(easter, 56), name: "Trinity Sunday", holyDay: false },
    { date: addDays(easter, 63), name: "Corpus Christi", holyDay: false },
  ];
}

function adventStart(year) {
  return nearestSunday(new Date(year, 10, 30)); // Sunday nearest Nov 30
}

// Returns { season, color, label } for a given date
function liturgicalInfo(date) {
  const y = date.getFullYear();
  const easterThis = computeEaster(y);
  const ashWed = addDays(easterThis, -46);
  const pentecost = addDays(easterThis, 49);
  const advent = adventStart(y);
  const christmas = new Date(y, 11, 25);
  const christmasPrevYear = new Date(y - 1, 11, 25);
  const baptismOfLord = addDays(new Date(y, 0, 6), 7); // rough: ~ a week after Epiphany

  const t = date.getTime();

  if (t >= christmasPrevYear.getTime() && t < baptismOfLord.getTime()) {
    return { season: 'Christmas', color: '#b8912f', dot: '#b8912f' };
  }
  if (t >= advent.getTime() && t < christmas.getTime()) {
    return { season: 'Advent', color: '#5b3a73', dot: '#5b3a73' };
  }
  if (t >= ashWed.getTime() && t < easterThis.getTime()) {
    return { season: 'Lent', color: '#5b3a73', dot: '#5b3a73' };
  }
  if (t >= easterThis.getTime() && t <= pentecost.getTime()) {
    return { season: 'Easter', color: '#b8912f', dot: '#b8912f' };
  }
  return { season: 'Ordinary Time', color: '#3f6e4e', dot: '#3f6e4e' };
}

function feastsForYear(year) {
  const list = [];
  FIXED_FEASTS.forEach(([m, d, name, holyDay]) => {
    list.push({ date: new Date(year, m - 1, d), name, holyDay, fixed: true });
  });
  movableFeasts(year).forEach(f => list.push({ date: f.date, name: f.name, holyDay: f.holyDay, fixed: false }));
  list.push({ date: adventStart(year), name: "First Sunday of Advent", holyDay: false, fixed: false });
  return list;
}
function feastsOnDate(date) {
  const year = date.getFullYear();
  const key = ymd(date);
  return feastsForYear(year).filter(f => ymd(f.date) === key);
}

