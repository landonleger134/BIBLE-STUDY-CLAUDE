async function loadOrCreateProfile(user) {
  let { data, error } = await sb.from('profiles').select('*').eq('id', user.id).maybeSingle();
  if (error) { toast('Could not load your profile.', true); return null; }
  if (!data) {
    // Trigger may not have fired yet (race on very first sign-in) — create it ourselves.
    const fallbackName = (user.email || 'member').split('@')[0];
    const { data: inserted, error: insErr } = await sb.from('profiles')
      .insert({ id: user.id, display_name: fallbackName })
      .select().single();
    if (insErr) { toast('Could not set up your profile.', true); return null; }
    data = inserted;
  }
  return data;
}

